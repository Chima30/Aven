#!/usr/bin/env node
/**
 * Builds the copy-paste SQL bundles from supabase/migrations/*.sql:
 *
 *   supabase/setup_all_in_one.sql   — EVERY migration, for a brand-new Supabase project
 *   supabase/upgrades/stageN.sql    — only that stage's migrations, for an existing project
 *
 * Stages are identified by the migration filename date (see STAGES below).
 * Run: npm run db:bundle   (a test fails if a bundle is out of date)
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const STAGES = {
  1: "20261031",
  2: "20261101",
  3: "20261102",
  4: "20261103",
  5: "20261104",
  6: "20261105",
};

function migrations(root) {
  const dir = join(root, "supabase", "migrations");
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((f) => ({ name: f, sql: readFileSync(join(dir, f), "utf8").trim() }));
}

function bundle(files, title, instructions) {
  const header = [
    "-- =============================================================================",
    `-- AVEN — ${title} (generated by npm run db:bundle; do not edit by hand)`,
    ...instructions.map((line) => `-- ${line}`),
    "-- It runs inside a single transaction: if anything fails, nothing is applied.",
    `-- Contains: ${files.map((f) => f.name).join(", ")}`,
    "-- =============================================================================",
    "",
    "begin;",
    "",
  ].join("\n");
  const body = files.map((f) => `-- >>> ${f.name}\n${f.sql}\n`).join("\n");
  return `${header}${body}\ncommit;\n`;
}

export function buildBundles(root = process.cwd()) {
  const all = migrations(root);
  const out = {
    "supabase/setup_all_in_one.sql": bundle(all, "FULL SETUP, ALL STAGES", [
      "Use this ONLY on a NEW, EMPTY Supabase project: SQL Editor → New query → paste → Run, once.",
      "If your project already has an earlier stage installed, run the files in supabase/upgrades/ instead.",
    ]),
  };
  for (const [stage, prefix] of Object.entries(STAGES)) {
    const files = all.filter((f) => f.name.startsWith(prefix));
    out[`supabase/upgrades/stage${stage}.sql`] = bundle(files, `UPGRADE: STAGE ${stage} ONLY`, [
      `Run this ONCE on a project that already has every stage before Stage ${stage}.`,
      "Run upgrades in order and never run the same one twice.",
    ]);
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(join(process.cwd(), "supabase", "upgrades"), { recursive: true });
  for (const [path, content] of Object.entries(buildBundles())) {
    writeFileSync(join(process.cwd(), path), content);
    console.log(`Wrote ${path}`);
  }
}
